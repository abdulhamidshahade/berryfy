CREATE TABLE users
	(
		id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
		user_name VARCHAR(256), 
		normalized_user_name VARCHAR(256), 
		email VARCHAR(256), 
		normalized_email VARCHAR(256), 
		email_confirmed BOOLEAN NOT NULL DEFAULT FALSE, 
		password_hash TEXT, 
		security_stamp TEXT, 
		concurrency_stamp TEXT, 
		phone_number TEXT, 
		phone_number_confirmed BOOLEAN NOT NULL DEFAULT FALSE, 
		twofactor_enabled BOOLEAN NOT NULL DEFAULT FALSE, 
		lockout_end TIMESTAMPTZ, 
		lockout_enabled BOOLEAN NOT NULL DEFAULT FALSE, 
		access_failed_count INTEGER NOT NULL DEFAULT 0, 
		firstname TEXT NOT NULL DEFAULT '', 
		lastname TEXT NOT NULL DEFAULT '', 
		email_confirmation_code TEXT, 
		email_confirmation_code_expiry TIMESTAMPTZ, 
		password_reset_code TEXT, 
		password_reset_code_expiry TIMESTAMPTZ, 
		refresh_token TEXT, 
		refresh_token_expiry TIMESTAMPTZ
	);