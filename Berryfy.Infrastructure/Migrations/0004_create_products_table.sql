-- Creates the products table (backs berryfy.domain.entities.productEntities.product).

CREATE TABLE products 
(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	shop_id BIGINT NOT NULL,
	global_category_id BIGINT,
    shop_category_id BIGINT,
	description TEXT NOT NULL,
	stock_quantity INTEGER NOT NULL DEFAULT 0,
	image_url TEXT NOT NULL,
	price NUMERIC(18,2) NOT NULL,
	reserved_stock INTEGER NOT NULL DEFAULT 0,
	low_stock_threshold INTEGER NOT NULL DEFAULT 5,
	is_active BOOLEAN NOT NULL DEFAULT TRUE,
	sku TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

	CONSTRAINT fk_products_shop
        FOREIGN KEY (shop_id)
        REFERENCES shops(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_products_global_category
        FOREIGN KEY (global_category_id)
        REFERENCES global_categories(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_products_shop_category
        FOREIGN KEY (shop_id, shop_category_id)
        REFERENCES shop_categories(shop_id, id)
        ON DELETE RESTRICT
);