CREATE TABLE shop_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    image_url TEXT,
    slug VARCHAR(180) NOT NULL,
    parent_category_id BIGINT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_shop_categories_shop
        FOREIGN KEY (shop_id)
        REFERENCES shops(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_shop_categories_shop_id
        UNIQUE (shop_id, id),

    CONSTRAINT uq_shop_categories_slug
        UNIQUE (shop_id, slug),

    CONSTRAINT fk_shop_categories_parent
        FOREIGN KEY (shop_id, parent_category_id)
        REFERENCES shop_categories(shop_id, id)
        ON DELETE RESTRICT
);